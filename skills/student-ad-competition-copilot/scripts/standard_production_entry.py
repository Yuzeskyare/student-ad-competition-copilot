"""Prepare a new request and run the unmodified package guard before native dispatch."""
import argparse
import json
import subprocess
import sys
import hashlib
import copy
import secrets
from datetime import datetime, timezone
from pathlib import Path

from review_contract import inside, load, bound_file, digest
from review_state import snapshot


class DispatchAlreadyReserved(ValueError):
    def __init__(self, path, record):
        super().__init__('This request or overlapping scope has an unresolved dispatch intent; recover the saved manifest, receipt and actual events; changing request ID or paths cannot authorize a retry')
        self.path, self.record = path, record


def intent_path(root, manifest, request_id):
    if not isinstance(request_id, str) or not request_id.strip():
        raise ValueError('Request ID is required')
    key = hashlib.sha256(json.dumps([manifest['run_id'], request_id], ensure_ascii=False).encode()).hexdigest()
    return inside(root, 'standard-dispatch-intents/'+key+'.json')


def existing_intent(root, path):
    try:
        record = load(path)
    except (OSError, ValueError):
        record = {'state': 'unreadable-intent; inspect before continuing'}
    return DispatchAlreadyReserved(path.relative_to(root).as_posix(), record)


def validate_parameters(params):
    allowed = {'prompt', 'referenced_image_paths', 'num_last_images_to_include', 'transparent_background'}
    if not isinstance(params, dict) or not set(params) <= allowed or not isinstance(params.get('prompt'), str) or not params['prompt'].strip():
        raise ValueError('Invalid native image parameters')
    refs = params.get('referenced_image_paths')
    if refs is not None and (not isinstance(refs, list) or not all(isinstance(p, str) and p.strip() and Path(p).is_absolute() for p in refs)):
        raise ValueError('Native references must be null or a list of absolute image paths')
    recent = params.get('num_last_images_to_include')
    if recent is not None and (type(recent) is not int or not 1 <= recent <= 5):
        raise ValueError('Recent image count must be null or an integer from 1 to 5')
    if 'transparent_background' in params and type(params['transparent_background']) is not bool:
        raise ValueError('transparent_background must be a boolean')
    if refs and recent is not None:
        raise ValueError('Choose one reference mechanism')
    return refs or []


def prepare(root, manifest, payload, destination):
    payload = copy.deepcopy(payload)
    base = Path(__file__).resolve().parent
    # The host body is package code too, not an author-provided dispatch adapter.
    inventory = {x['path']: x['sha256'] for x in load(base.parent/'version.json')['files']}
    if inventory.get('scripts/standard_production_entry.js') != digest(base/'standard_production_entry.js'):
        raise ValueError('Standard host entry differs from package inventory')
    q = payload['request']
    if q.get('operation') != 'external' or q.get('tool') != 'image_gen.imagegen' or 'command' in q:
        raise ValueError('This standard entry supports the native image_gen.imagegen tool only')
    params = q.get('parameters')
    refs = validate_parameters(params)
    bound_inputs = {inside(root, p) for p in payload['input_paths']}
    for p in refs:
        if Path(p).resolve() not in bound_inputs:
            raise ValueError('Every native image reference must be a hashed request input')
    intent = intent_path(root, manifest, q['id'])
    if intent.exists():
        raise existing_intent(root, intent)
    # A unique invocation identity travels in the real, logged tool arguments.
    # It is not a visual instruction or an author-supplied completion claim.
    if 'dispatch_nonce' in q:
        raise ValueError('Dispatch identity is generated by the standard entry only')
    q['dispatch_nonce'] = secrets.token_hex(24)
    q['parameters']['prompt'] += dispatch_suffix(q['dispatch_nonce'])
    prepared = snapshot(root, manifest, 'request', payload, destination)
    receipt_path = destination.rstrip('/') + '/dispatch-guard.json'
    command = [sys.executable, '-X', 'utf8', '-B', str(base/'guard_production.py'),
               '--run-dir', str(root), '--manifest', prepared['manifest']['path'],
               '--request-id', q['id'], '--output', receipt_path]
    process = subprocess.run(command, capture_output=True, text=True, encoding='utf-8', timeout=120)
    if process.returncode:
        raise ValueError('Package guard blocked dispatch: ' + (process.stdout + process.stderr).strip())
    receipt = load(inside(root, receipt_path))
    if (receipt.get('status') != 'authorized' or receipt.get('dispatch_checked') is not True
            or receipt.get('executed') is not False or receipt.get('production_state') != 'authorized'):
        raise ValueError('Package guard did not authorize dispatch')
    current = load(bound_file(root, prepared['manifest']))
    contract = load(inside(root, current['review_contract']))
    registered = [r for r in contract['production_requests'] if r['sha256'] == receipt['request_sha256']]
    if len(registered) != 1 or load(bound_file(root, registered[0])) != receipt['request']:
        raise ValueError('Checked request changed before native dispatch')
    checked = dict(status='ready-for-native-dispatch', manifest=prepared['manifest'],
                receipt=dict(path=receipt_path, sha256=digest(inside(root, receipt_path))),
                tool=receipt['request']['tool'], parameters=receipt['request']['parameters'],
                request_id=receipt['request_id'], content_pass_granted=False)
    # Atomically reserve once per run/request, across snapshot branches. This is
    # an intent, NOT proof the native tool started, finished or released an image.
    intent.parent.mkdir(parents=True, exist_ok=True)
    record = dict(kind='standard-dispatch-intent', run_id=manifest['run_id'],
                  request_id=q['id'], recorded_at=datetime.now(timezone.utc).isoformat(),
                  native_execution='unknown', checked=checked)
    from dispatch_reservation import reserve
    reserve(root, current, receipt['request'], intent, record)
    checked['dispatch_intent'] = dict(path=intent.relative_to(root).as_posix(), sha256=digest(intent))
    return checked


def dispatch_suffix(nonce):
    import re
    if not isinstance(nonce, str) or not re.fullmatch(r'[0-9a-f]{48}', nonce):
        raise ValueError('Invalid standard dispatch identity')
    return '\n\n[Production trace metadata; do not render as artwork or copy: ' + nonce + ']'


def content_parameters(request):
    """Recover exact authored parameters without interpreting their language."""
    params = dict(request['parameters'])
    suffix = dispatch_suffix(request['dispatch_nonce'])
    if not params['prompt'].endswith(suffix):
        raise ValueError('Native prompt differs from its dispatch identity')
    params['prompt'] = params['prompt'][:-len(suffix)]
    return params


def main():
    p = argparse.ArgumentParser(description=__doc__)
    for key in ('run-dir', 'manifest', 'payload', 'snapshot'):
        p.add_argument('--'+key, required=True)
    args = p.parse_args()
    try:
        root = Path(args.run_dir).resolve()
        result = prepare(root, load(inside(root, args.manifest)), load(inside(root, args.payload)), args.snapshot)
        print(json.dumps(result, ensure_ascii=False))
        return 0
    except DispatchAlreadyReserved as exc:
        print(json.dumps(dict(status='blocked', reason=str(exc), native_execution='unknown',
                              dispatch_intent=exc.path, checked=exc.record.get('checked'),
                              recovery='Resume from checked.manifest and reconcile actual native events. Do not delete the intent or fork a retry.'), ensure_ascii=False))
        return 1
    except (OSError, ValueError, KeyError, TypeError, subprocess.TimeoutExpired) as exc:
        print(json.dumps(dict(status='blocked', reason=str(exc), executed=False), ensure_ascii=False))
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
